"""tm.shortlist: the handoff's pb2/trend_shortlist.py, ported for every playbook.

The golden file was made by running the reference tool on the LD dry run's trend files (see
fixtures/shortlist/README.md); the port must give the same JSON.
"""

import ast
import json
from datetime import date
from pathlib import Path

import pytest

import ld
from tm import shortlist, trends
from tm.cli import main
from tm.playbooks import TREND_RESEARCH
from tm.runfolder import RunFolder

REPO = Path(__file__).resolve().parents[4]
LD = ld.TRENDS
ORIGINAL = REPO / "handoff" / "creative-brief_v02" / "tools" / "pb2" / "trend_shortlist.py"
GOLDEN = Path(__file__).parent / "fixtures" / "shortlist"
TERMS = "lucid dream,dream,sleep,night,journal,wake up,4am,consciousness"


def _run(tmp_path) -> RunFolder:
    return RunFolder.create(tmp_path, "ld", date(2026, 11, 7), playbook=TREND_RESEARCH)


def _shortlist(run: RunFolder, capsys, *extra: str) -> tuple[dict, dict]:
    """Run the command; return its --json answer and the JSON file it wrote."""
    assert main(["trends", "shortlist", "--run", str(run.path), "--terms", TERMS, "--today", "2026-11-04",
                 *extra, "--json"]) == 0
    out = json.loads(capsys.readouterr().out)
    return out, json.loads((run.path / out["json"]).read_text(encoding="utf-8"))


def _without_inputs(payload: dict) -> dict:
    return {**payload, "meta": {k: v for k, v in payload["meta"].items() if k != "inputs"}}


def _literal(path: Path, name: str):
    tree = ast.parse(path.read_text(encoding="utf-8"))
    for node in tree.body:
        if isinstance(node, ast.Assign) and any(getattr(t, "id", None) == name for t in node.targets):
            try:
                return ast.literal_eval(node.value)
            except ValueError:                       # STOPWORDS: "...".split(), no names needed
                return eval(compile(ast.Expression(node.value), str(path), "eval"), {"__builtins__": {}})
    raise AssertionError(f"{name} not in {path}")


@pytest.mark.private_data
def test_shortlist_matches_original_tool_on_ld_dry_run(tmp_path, capsys):
    run = _run(tmp_path)
    out, mine = _shortlist(run, capsys, "--inputs", str(LD / "*.json"))
    golden = json.loads((GOLDEN / "golden_v02.json").read_text(encoding="utf-8"))
    assert _without_inputs(mine) == _without_inputs(golden)
    assert [Path(p).name for p in mine["meta"]["inputs"]] == [Path(p).name for p in golden["meta"]["inputs"]]
    assert out["json"] == "03_wip/trend_shortlist_v01.json" and out["md"] == "03_wip/trend_shortlist_v01.md"
    assert out["pool_size"] == 124 and out["hooks"] == 38 and out["topics"] == 11

    md = (run.path / out["md"]).read_text(encoding="utf-8")
    want = (GOLDEN / "golden_v02.md").read_text(encoding="utf-8")
    assert md == want.replace("Generated by `tools/pb2/trend_shortlist.py`.", "Generated by `tm trends shortlist`.")

    # Never overwritten: a second run is _v02, beside the first.
    out2, _ = _shortlist(run, capsys, "--inputs", str(LD / "*.json"))
    assert out2["json"] == "03_wip/trend_shortlist_v02.json" and out2["md"] == "03_wip/trend_shortlist_v02.md"
    assert (run.path / out["json"]).is_file()


@pytest.mark.private_data
def test_constants_are_the_originals_verbatim():
    for name in ("HOOK_WEIGHTS", "STATUS_MULT", "MOMENTUM_SCORE", "MOMENTUM_OTHER", "SENSITIVITY_MULT",
                 "CREATORS_CAP", "LIFT_UNKNOWN", "CONTRADICTION_STATUS_COST", "HOOK_FIT_BONUS_MAX",
                 "FIELD_WEIGHTS", "TOPIC_REL_SHARE", "TOPIC_REL_SCALE", "SPIKE_MAX_DAYS", "STOPWORDS",
                 "SCRIPTS", "LICENCE_KEYS"):
        assert getattr(shortlist, name) == _literal(ORIGINAL, name), name
    tree = ast.parse(ORIGINAL.read_text(encoding="utf-8"))
    pairs = [n for n in tree.body if isinstance(n, ast.Assign) and isinstance(n.targets[0], ast.Tuple)]
    names = [e.id for n in pairs for e in n.targets[0].elts]
    assert names == ["LANG_MATCH", "LANG_INFERRED", "LANG_UNKNOWN", "LANG_FOREIGN", "ADOPTION_FULL_PCT",
                     "ADOPTION_UNKNOWN", "RECENCY_FULL_DAYS", "RECENCY_ZERO_DAYS", "PENALTY_EXCLUDE",
                     "PENALTY_NOISE", "PENALTY_PROPER_NAME", "PENALTY_SPIKE"]
    for n in pairs:
        for target, value in zip(n.targets[0].elts, ast.literal_eval(n.value)):
            assert getattr(shortlist, target.id) == value, target.id
    assert trends.DEFAULT_NOISE == _literal(ORIGINAL, "DEFAULT_NOISE")
    assert not hasattr(shortlist, "DEFAULT_NOISE")                  # one copy, in tm.trends


@pytest.mark.private_data
def test_plugin_saved_answers_give_the_same_shortlist(tmp_path, capsys):
    """The LD files saved as the collector saves them: labels from `_input.about`, trend details
    as `detail:<id>`, video pages joined to their trend by `_input.trend_id`."""
    run = _run(tmp_path)
    ld.save_trends(run, search_limit=50)                                # two video pages each, MCP envelope
    trends.save_answer(run, "get_usage", {}, {"plan": "agent"})        # not a trend: never read
    out, mine = _shortlist(run, capsys)                                 # the run's own answers by default
    golden = json.loads((GOLDEN / "golden_v02.json").read_text(encoding="utf-8"))

    def by_id(payload):                                                 # file order differs (slugs are lowercase)
        rows = {}
        for key in ("hooks", "topics", "formats", "sounds"):
            for r in payload[key]:
                rows[r["id"]] = {**r, "found_by": sorted(r["found_by"])}
        return rows
    assert by_id(mine) == by_id(golden)
    assert _without_inputs(mine)["meta"] == _without_inputs(golden)["meta"]
    assert len(mine["meta"]["inputs"]) == 9 + 1 + 10 + 20
    assert all(not p.startswith("02_research/usage") for p in mine["meta"]["inputs"])


def test_load_pool_labels_plugin_and_legacy_files(tmp_path):
    run = _run(tmp_path)
    card = {"id": "abcdef1234", "kind": "topic_trend", "name": "Dream diary", "status": "confirmed"}
    s1 = trends.save_answer(run, "search_trends", {"about": "Dream Journal"}, {"data": [card], "has_more": True})
    s2 = trends.save_answer(run, "search_trends", {"about": "Dream Journal", "page": 2}, {"data": [], "has_more": False})
    lst = trends.save_answer(run, "list_trends", {"sort": "rising", "trend_type": "topic"}, {"data": [card]})
    det = trends.save_answer(run, "get_trend", {"trend_id": "abcdef1234"}, {**card, "name": "Dream diary (detail)"})
    vid = trends.save_answer(run, "get_trend_videos", {"trend_id": "abcdef1234"},
                             {"data": [{"asset_id": "v1", "excerpt": "my dream"}], "page": 1, "has_more": False})
    legacy = tmp_path / "search_sleep_tips.json"
    legacy.write_text(json.dumps([card]), encoding="utf-8")
    page2 = trends.save_answer(run, "get_trend_videos", {"trend_id": "abcdef1234", "page": 2},
                               {"data": ["not a video", {"asset_id": "v2"}, {"asset_id": "v1"}], "page": 2})
    odd = tmp_path / "odd.json"
    odd.write_text(json.dumps([1, 2]), encoding="utf-8")
    pool, found_by = shortlist.load_pool([s1, s2, lst, legacy, det, vid, page2, odd])
    assert found_by["abcdef1234"] == ["Dream Journal", "rising:topic", "sleep tips", "detail:abcdef12"]
    assert pool["abcdef1234"]["name"] == "Dream diary (detail)"           # a detail answer wins
    assert [e["asset_id"] for e in pool["abcdef1234"]["examples"]] == ["v1", "v2"]
    assert list(pool) == ["abcdef1234"]


def test_detail_without_trend_id_is_labelled_by_its_card(tmp_path):
    """A saved get_trend answer whose `_input` lacks `trend_id` (written by hand) is labelled by the
    card's own id, else by the file name as the reference tool did; never a bare "detail:"."""
    folder = tmp_path / "02_research"
    folder.mkdir()
    card = {"id": "abcdef1234", "kind": "topic_trend", "name": "Dream diary (detail)", "status": "confirmed"}
    by_card = folder / "by_hand.json"
    by_card.write_text(json.dumps({"_tool": "get_trend", "_input": {}, "answer": card}), encoding="utf-8")
    no_card = folder / "trend_9876543210.json"
    no_card.write_text(json.dumps({"_tool": "get_trend", "_input": None, "answer": {"data": []}}), encoding="utf-8")
    assert shortlist._read_file(by_card)[:2] == ("trends", "detail:abcdef12")
    assert shortlist._read_file(no_card)[:2] == ("trends", "detail:98765432")
    search = folder / "search_dream.json"
    search.write_text(json.dumps([{**card, "name": "Dream diary"}]), encoding="utf-8")
    pool, found_by = shortlist.load_pool([search, by_card])
    assert found_by["abcdef1234"] == ["dream", "detail:abcdef12"]
    assert pool["abcdef1234"]["name"] == "Dream diary (detail)"           # still wins as a detail answer


def test_sounds_commercial_only_keeps_licensed_sounds(tmp_path, capsys):
    """Sound cards carry their licence in whatever field TrendsMesh uses; --sounds-commercial-only
    drops every sound not marked commercial, and without it the others are flagged (CB9)."""
    run = _run(tmp_path)
    base = {"kind": "sound_trend", "what_it_is": "a dreamy night sound", "status": "confirmed", "momentum": "rising",
            "reach": {"creators": 30, "views": 50000}, "since": "2026-10-20T00:00:00Z", "active_for_days": 12}
    cards = [{**base, "id": "s-ads", "name": "Dream pop loop", "license": "Commercial use allowed"},
             {**base, "id": "s-bool", "name": "Sleep piano", "commercial_use": True},
             {**base, "id": "s-org", "name": "Night rain", "licence_type": "organic only"},
             {**base, "id": "s-none", "name": "Lucid hum"}]
    trends.save_answer(run, "search_trends", {"about": "dream sounds"}, {"data": cards})
    _, every = _shortlist(run, capsys)
    licences = {r["id"]: r["licence"] for r in every["sounds"]}
    assert licences == {"s-ads": "commercial", "s-bool": "commercial", "s-org": "organic", "s-none": "unknown"}
    flags = {r["id"]: r["flags"] for r in every["sounds"]}
    assert "organic only: in ads use a licensed equivalent (CB9)" in flags["s-org"]
    assert "licence unknown: treat as organic only (CB9)" in flags["s-none"]
    assert not any("CB9" in f for f in flags["s-ads"] + flags["s-bool"])
    assert every["meta"]["dropped"]["sound_not_commercial"] == 0

    out, only = _shortlist(run, capsys, "--sounds-commercial-only")
    assert sorted(r["id"] for r in only["sounds"]) == ["s-ads", "s-bool"]
    assert only["meta"]["sounds_commercial_only"] is True
    assert only["meta"]["dropped"]["sound_not_commercial"] == 2
    assert out["sounds"] == 2 and out["json"] == "03_wip/trend_shortlist_v02.json"


def test_never_writes_no_category_trend(tmp_path, capsys):
    """Nothing matches the terms: the topic list is filled with the best-signal topics that carry
    no noise flag, marked "weak fit (no term match)", never "no category trend"."""
    run = _run(tmp_path)
    cards = [
        {"id": f"t{i}", "kind": "topic_trend", "name": name, "what_it_is": "", "status": "confirmed",
         "momentum": "rising", "reach": {"creators": creators, "views": 1000}, "since": "2026-10-20T00:00:00Z",
         "active_for_days": 10}
        for i, (name, creators) in enumerate([("Glass skin routine", 40), ("Cat cafes", 5),
                                              ("Election day memes", 60), ("Desk setups", 20)])]
    trends.save_answer(run, "search_trends", {"about": "lucid dreaming"}, {"data": cards})
    _, mine = _shortlist(run, capsys)
    assert [r["name"] for r in mine["topics"]] == ["Glass skin routine", "Desk setups", "Cat cafes"]
    assert all("weak fit (no term match)" in r["flags"] for r in mine["topics"])
    assert all(r["reason"].startswith("weak fit (no term match), shown as best available signal")
               for r in mine["topics"])
    assert mine["meta"]["dropped"]["no_term_relevance"] == 4
    md = (run.path / "03_wip" / "trend_shortlist_v01.md").read_text(encoding="utf-8").lower()
    assert "no category trend" not in md and "no trends in the category" not in md
    assert "glass skin routine" in md

    result = shortlist.score_all({c["id"]: c for c in cards}, {}, ["dream"], [], "en", date(2026, 11, 4),
                                 trends.DEFAULT_NOISE, min_topics=0)
    assert result["topics"] == []                                         # filled only up to --min-topics


def test_contradicted_excluded(tmp_path, capsys):
    run = _run(tmp_path)
    base = {"kind": "topic_trend", "what_it_is": "people log their dreams each morning",
            "reach": {"creators": 30, "views": 50000}, "since": "2026-10-20T00:00:00Z", "active_for_days": 12}
    cards = [{**base, "id": "keep", "name": "Dream journal mornings", "status": "confirmed"},
             {**base, "id": "gone", "name": "Dream journal nights", "status": "contradicted"},
             {**base, "id": "hook", "kind": "hook_trend", "name": "my dream _", "status": "contradicted"}]
    trends.save_answer(run, "search_trends", {"about": "dream journal"}, {"data": cards})
    _, mine = _shortlist(run, capsys)
    listed = [r["id"] for key in ("hooks", "topics", "formats", "sounds", "hooks_beyond_top", "topics_beyond_top")
              for r in mine[key]]
    assert listed == ["keep"]
    assert mine["meta"]["dropped"]["contradicted"] == 2


def test_errors_are_said(tmp_path, capsys):
    run = _run(tmp_path)
    assert main(["trends", "shortlist", "--run", str(run.path), "--terms", "dream", "--json"]) == 1
    message = json.loads(capsys.readouterr().out)["message"]
    assert "No saved TrendsMesh answers" in message and "continues from the same place" in message
    assert main(["trends", "shortlist", "--run", str(run.path), "--terms", " , ", "--json"]) == 1
    assert "--terms" in json.loads(capsys.readouterr().out)["message"]
    bad = run.path / "02_research" / "search" / "search_bad.json"
    bad.parent.mkdir(parents=True)
    bad.write_text("{not json", encoding="utf-8")
    trends.save_answer(run, "search_trends", {"about": "dream"}, {"data": [
        {"id": "t1", "kind": "topic_trend", "name": "Dream diary", "status": "confirmed"}]})
    assert main(["trends", "shortlist", "--run", str(run.path), "--terms", "dream", "--json"]) == 0
    out = json.loads(capsys.readouterr().out)
    assert out["skipped"] == ["02_research/search/search_bad.json"] and out["topics"] == 1
